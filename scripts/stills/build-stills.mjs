// "Story in stills" pipeline: six chapter images → optimised WebP + the manifest module that turns the section on.
//
//   npm run stills:build                # story-stills-src/scene-01 … scene-06 (.png/.jpg/.jpeg/.webp) → public/story-stills
//   npm run stills:clean                # remove the output; the section disappears from the site again
//
// Optional: story-stills-src/alt.json  { "scene-01": "what the image shows", … }  (screen-reader descriptions)
// Replacing the crops with real scene images later = drop the new files in story-stills-src (same names) and rebuild.
import sharp from "sharp";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const SRC = join(ROOT, "story-stills-src");
const OUT = join(ROOT, "public", "story-stills");
const MANIFEST_TS = join(ROOT, "app", "components", "site", "stills", "stillsManifest.generated.ts");
const COUNT = 6;
const LG = { max: 1400, q: 82 };
const SM = { max: 720, q: 74 };

const writeManifest = (m) =>
  writeFileSync(
    MANIFEST_TS,
    `/* GENERATED by scripts/stills/build-stills.mjs — do not edit by hand.
   null = no chapter images yet, so the section is not rendered at all. */
import type { StillsManifest } from "../../../lib/stills";

export const STILLS_MANIFEST: StillsManifest | null = ${m ? JSON.stringify(m, null, 2) : "null"};
`,
  );

if (process.argv.includes("--clean")) {
  rmSync(OUT, { recursive: true, force: true });
  writeManifest(null);
  console.log("Removed public/story-stills and reset the manifest: the section is hidden again.");
  process.exit(0);
}

const fail = (msg) => {
  console.error(`✖ ${msg}`);
  process.exit(1);
};
let alts = {};
if (existsSync(join(SRC, "alt.json"))) {
  try {
    alts = JSON.parse(readFileSync(join(SRC, "alt.json"), "utf8"));
  } catch {
    fail("story-stills-src/alt.json is not valid JSON.");
  }
}

// validate everything before writing anything
const sources = [];
for (let i = 1; i <= COUNT; i++) {
  const name = `scene-${String(i).padStart(2, "0")}`;
  const file = ["png", "jpg", "jpeg", "webp"].map((e) => join(SRC, `${name}.${e}`)).find((p) => existsSync(p));
  if (!file) fail(`Missing ${name} (.png/.jpg/.webp) in ${SRC}. Run \`npm run stills:crop\` or add your own image.`);
  const m = await sharp(file).metadata();
  if (!m.width || !m.height) fail(`${file} is not a readable image.`);
  if (m.height < 600) console.warn(`⚠ ${name} is only ${m.width}×${m.height}; it may look soft on large screens.`);
  sources.push({ name, file });
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
const images = [];
let bytes = 0;
for (const { name, file } of sources) {
  const lg = await sharp(file).resize(LG.max, LG.max, { fit: "inside", withoutEnlargement: true }).webp({ quality: LG.q, effort: 5 }).toFile(join(OUT, `${name}-lg.webp`));
  const sm = await sharp(file).resize(SM.max, SM.max, { fit: "inside", withoutEnlargement: true }).webp({ quality: SM.q, effort: 5 }).toFile(join(OUT, `${name}-sm.webp`));
  bytes += lg.size + sm.size;
  const alt = typeof alts[name] === "string" ? alts[name].trim() : "";
  if (!alt) console.warn(`⚠ ${name}: no description in alt.json (screen readers will get the chapter title only).`);
  images.push({ lg: `${name}-lg.webp`, sm: `${name}-sm.webp`, w: lg.width, h: lg.height, alt });
  console.log(`✔ ${name}: ${lg.width}×${lg.height} (${Math.round(lg.size / 1024)} KB) + small (${Math.round(sm.size / 1024)} KB)`);
}
writeManifest({ version: 1, images });
console.log(`\nDone: ${COUNT} images, ${(bytes / 1024).toFixed(0)} KB in total. The section is now live after the hero.`);
