// Journey story asset pipeline: your exported frames + recordings → optimised site assets + manifest.
//
//   npm run journey:build                 # read ./journey-src, write public/journey + the manifest module
//   npm run journey:build -- --src D:/renders/journey
//   npm run journey:preview               # labelled TEST frames + tones (see preview-journey.mjs); dev only
//   npm run journey:clean                 # remove the generated assets; the story disappears from the site again
//
// Source layout (any frame file names; they are sorted naturally, so frame2 comes before frame10):
//   journey-src/
//     dream/        *.png | *.jpg | *.jpeg | *.webp   (one continuous sequence per scene, ≥ 2 frames)
//     beginning/  learning/  projects/  experience/  future/
//     audio/        narration-scene-01.mp3 … narration-scene-06.mp3, background-music.mp3   (mp3/m4a/ogg/wav; optional)
//     subtitles/    scene-01.vtt … scene-06.vtt   (or .srt — converted to WebVTT; optional)
//     poster.webp   (optional; defaults to the first frame of "dream")
//
// Output: public/journey/images/<scene>/{desktop,mobile}/frame-001.webp …, public/journey/audio, public/journey/subtitles,
// public/journey/poster/journey-poster.webp and app/components/site/story/journeyManifest.generated.ts.
// Nothing here invents content: missing narration/subtitles/music are simply left out (the story then runs silent).
import sharp from "sharp";
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};
const SRC = arg("src", join(ROOT, "journey-src"));
const OUT = join(ROOT, "public", "journey");
const MANIFEST_TS = join(ROOT, "app", "components", "site", "story", "journeyManifest.generated.ts");
const SCENES = ["dream", "beginning", "learning", "projects", "experience", "future"];
const SIZES = { desktop: { w: 1600, h: 900, q: 78 }, mobile: { w: 800, h: 450, q: 72 } };
const IMG = /\.(png|jpe?g|webp)$/i;
const AUDIO = [".mp3", ".m4a", ".ogg", ".wav"];

const writeManifestModule = (manifest) =>
  writeFileSync(
    MANIFEST_TS,
    `/* GENERATED by scripts/journey/build-journey.mjs — do not edit by hand.
   null = no real story assets yet, so the story section is not rendered at all (no placeholders on the site). */
import type { StoryManifest } from "../../../lib/story";

export const JOURNEY_MANIFEST: StoryManifest | null = ${manifest ? JSON.stringify(manifest, null, 2) : "null"};
`,
  );

if (process.argv.includes("--clean")) {
  rmSync(OUT, { recursive: true, force: true });
  writeManifestModule(null);
  console.log("Removed public/journey and reset the manifest: the story is hidden again.");
  process.exit(0);
}

const fail = (msg) => {
  console.error(`✖ ${msg}`);
  process.exit(1);
};
if (!existsSync(SRC)) fail(`Source folder not found: ${SRC}\n  Create it with one folder of frames per scene (see the header of this script).`);

const natural = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });
const findFile = (dir, base, exts) => exts.map((e) => join(dir, base + e)).find((p) => existsSync(p)) ?? null;

// ── validate the frames before writing anything ──
const plan = [];
for (const id of SCENES) {
  const dir = join(SRC, id);
  if (!existsSync(dir)) fail(`Missing scene folder: ${dir}`);
  const files = readdirSync(dir).filter((f) => IMG.test(f) && statSync(join(dir, f)).isFile()).sort(natural);
  if (files.length < 2) fail(`Scene "${id}" needs at least 2 frames (found ${files.length}).`);
  const dims = new Set();
  for (const f of files) {
    const m = await sharp(join(dir, f)).metadata();
    dims.add(`${m.width}x${m.height}`);
  }
  if (dims.size > 1) console.warn(`⚠ Scene "${id}": frames have different sizes (${[...dims].join(", ")}) — they will be cropped to 16:9, but a consistent render size avoids jumps.`);
  plan.push({ id, dir, files });
}

// ── frames → WebP (desktop + mobile), cover-cropped to 16:9 ──
rmSync(join(OUT, "images"), { recursive: true, force: true });
let bytes = 0;
const scenes = [];
for (const [si, { id, dir, files }] of plan.entries()) {
  for (const [tier, s] of Object.entries(SIZES)) {
    const outDir = join(OUT, "images", id, tier);
    mkdirSync(outDir, { recursive: true });
    for (const [i, f] of files.entries()) {
      const out = join(outDir, `frame-${String(i + 1).padStart(3, "0")}.webp`);
      const info = await sharp(join(dir, f)).resize(s.w, s.h, { fit: "cover", position: "centre" }).webp({ quality: s.q, effort: 5 }).toFile(out);
      bytes += info.size;
    }
  }
  // audio + subtitles for this scene (optional)
  const n = String(si + 1).padStart(2, "0");
  const audioSrc = findFile(join(SRC, "audio"), `narration-scene-${n}`, AUDIO);
  let narration = null;
  if (audioSrc) {
    mkdirSync(join(OUT, "audio"), { recursive: true });
    narration = `narration-scene-${n}${extname(audioSrc).toLowerCase()}`;
    copyFileSync(audioSrc, join(OUT, "audio", narration));
  }
  const subSrc = findFile(join(SRC, "subtitles"), `scene-${n}`, [".vtt", ".srt"]);
  let subtitles = null;
  if (subSrc) {
    mkdirSync(join(OUT, "subtitles"), { recursive: true });
    let text = readFileSync(subSrc, "utf8").replace(/\r/g, "");
    if (subSrc.toLowerCase().endsWith(".srt")) text = "WEBVTT\n\n" + text.replace(/(\d\d:\d\d:\d\d),(\d{3})/g, "$1.$2");
    if (!text.startsWith("WEBVTT")) fail(`${subSrc} is not a WebVTT file (it must start with "WEBVTT").`);
    subtitles = `scene-${n}.vtt`;
    writeFileSync(join(OUT, "subtitles", subtitles), text);
  }
  scenes.push({ id, frames: files.length, narration, subtitles });
  console.log(`✔ ${id}: ${files.length} frames${narration ? ", narration" : ""}${subtitles ? ", subtitles" : ""}`);
}

const musicSrc = findFile(join(SRC, "audio"), "background-music", AUDIO);
let music = null;
if (musicSrc) {
  music = `background-music${extname(musicSrc).toLowerCase()}`;
  copyFileSync(musicSrc, join(OUT, "audio", music));
}

mkdirSync(join(OUT, "poster"), { recursive: true });
const posterSrc = findFile(SRC, "poster", [".webp", ".png", ".jpg", ".jpeg"]) ?? join(plan[0].dir, plan[0].files[0]);
await sharp(posterSrc).resize(SIZES.desktop.w, SIZES.desktop.h, { fit: "cover" }).webp({ quality: 80 }).toFile(join(OUT, "poster", "journey-poster.webp"));

const manifest = {
  version: 1,
  sizes: { desktop: { w: SIZES.desktop.w, h: SIZES.desktop.h }, mobile: { w: SIZES.mobile.w, h: SIZES.mobile.h } },
  scenes,
  music,
  poster: "journey-poster.webp",
  ...(process.argv.includes("--preview") ? { preview: true } : {}),
};
writeManifestModule(manifest);
console.log(`\nDone: ${scenes.reduce((a, s) => a + s.frames, 0)} frames × 2 sizes = ${(bytes / 1024 / 1024).toFixed(1)} MB of WebP.`);
console.log(`Music: ${music ?? "none"} · ${process.argv.includes("--preview") ? "preview build (development only)." : "the story section is now live in the site."}`);
